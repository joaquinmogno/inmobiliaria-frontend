import { expect, test } from '@playwright/test';

for (const width of [1280, 1366]) {
  test(`el formulario real guarda y recupera acuerdos, servicios, centavos y documentos a ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: width === 1280 ? 720 : 768 });
    await page.goto('/login');
    await page.getByPlaceholder('ejemplo@correo.com').fill('admin.integration@example.com');
    await page.getByPlaceholder('••••••••').fill('ProdTest!2026_Strong');
    const authenticated = page.waitForResponse(response => response.url().endsWith('/api/auth/login'));
    await page.getByRole('button', { name: /Ingresar a mi cuenta/i }).click();
    const { csrfToken } = await (await authenticated).json();
    await expect(page).toHaveURL(/\/home$/);
    const api = (url: string, method = 'GET', data?: unknown) => page.evaluate(async ({ url, method, data, csrfToken }) => {
      const response = await fetch(url, { method, credentials: 'include', headers: { 'content-type': 'application/json', 'x-csrf-token': csrfToken }, ...(data === undefined ? {} : { body: JSON.stringify(data) }) });
      return { status: response.status, text: await response.text() };
    }, { url, method, data, csrfToken });
    const name = `Borrador navegador ${width} ${Date.now()}`;
    const accountResponse = await api('/api/cuentas-bancarias', 'POST', { nombre: name, banco: 'Banco QA', moneda: 'USD' });
    expect(accountResponse.status, accountResponse.text).toBe(201);
    const account = JSON.parse(accountResponse.text);
    await page.goto('/contratos');
    await page.getByRole('button', { name: 'Nuevo contrato' }).click();
    const dialog = page.getByRole('dialog');
    await dialog.locator('#contract-property-address').fill(name);
    await dialog.getByRole('button', { name: 'Moneda del contrato', exact: false }).click();
    await page.getByRole('option', { name: /USD.*Dólares estadounidenses/ }).click();
    await dialog.locator('#contract-rent-amount').fill('1000,25');
    await dialog.locator('#contract-rent-amount').press('Tab');
    await dialog.getByRole('button', { name: 'Cobro acordado con inquilino', exact: false }).click();
    await page.getByRole('option', { name: 'Transferencia', exact: true }).click();
    await dialog.getByRole('button', { name: 'Cuenta acordada para recibir la transferencia', exact: false }).click();
    await page.getByRole('option', { name: `Banco QA · ${name}`, exact: true }).click();
    await dialog.getByRole('button', { name: 'Pago acordado con propietario', exact: false }).click();
    await page.getByRole('option', { name: 'Cheque', exact: true }).click();
    await dialog.getByRole('button', { name: 'Agregar concepto', exact: true }).click();
    await dialog.getByRole('button', { name: 'Servicio o gasto 1', exact: false }).click();
    await page.getByRole('option', { name: 'LUZ', exact: true }).click();
    await dialog.getByRole('button', { name: 'Responsable de LUZ', exact: false }).click();
    await page.getByRole('option', { name: 'Propietario', exact: true }).click();
    await dialog.locator('#contract-main-file').setInputFiles({ name: 'borrador-real.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n1 0 obj << /Type /Catalog >> endobj\n%%EOF') });
    await dialog.locator('[name="observacionDocumento"]').fill('Nota que debe recuperarse');
    const savedResponse = page.waitForResponse(response => response.url().endsWith('/api/contratos/borradores') && response.request().method() === 'POST');
    await dialog.getByRole('button', { name: 'Guardar borrador', exact: true }).focus();
    await page.keyboard.press('Enter');
    const response = await savedResponse;
    expect(response.status()).toBe(201);
    const saved = await response.json();
    expect(saved.datos.form).toMatchObject({ montoAlquiler: '1000.25', moneda: 'USD', modalidadCobroInquilino: 'TRANSFERENCIA', modalidadPagoPropietario: 'CHEQUE', cuentaCobroAcordadaId: String(account.id), serviciosGastos: [{ concepto: 'LUZ', responsable: 'PROPIETARIO' }] });
    await expect(page.getByText('Borrador guardado. Podés retomarlo cuando quieras.', { exact: true })).toBeVisible();
    await page.reload();
    await page.getByRole('button', { name: /^Borradores/ }).click();
    const row = page.getByLabel('Borradores de contratos').getByRole('listitem').filter({ hasText: name });
    await row.getByRole('button', { name: 'Continuar', exact: true }).click();
    await expect(dialog.locator('#contract-property-address')).toHaveValue(name);
    await expect(dialog.getByRole('button', { name: 'Cobro acordado con inquilino', exact: false })).toContainText('Transferencia');
    await expect(dialog.getByRole('button', { name: 'Pago acordado con propietario', exact: false })).toContainText('Cheque');
    await expect(dialog.getByRole('button', { name: 'Cuenta acordada para recibir la transferencia', exact: false })).toContainText(name);
    await expect(dialog.getByRole('button', { name: 'Responsable de LUZ', exact: false })).toContainText('Propietario');
    await expect(dialog.locator('[name="observacionDocumento"]')).toHaveValue('Nota que debe recuperarse');
    const getSaved = await api(`/api/contratos/borradores/${saved.id}`);
    const recovered = JSON.parse(getSaved.text);
    expect(recovered.datos).toEqual(saved.datos); expect(recovered.adjuntos).toHaveLength(1);
    const attachment = await api(`/api/files/${recovered.adjuntos[0].rutaArchivo}`);
    expect(attachment.status).toBe(200);
    await expect(dialog.getByLabel('Documentos guardados en el borrador')).toContainText('borrador-real.pdf');
    await dialog.getByRole('button', { name: 'Guardar borrador', exact: true }).focus();
    await expect(dialog.getByRole('button', { name: 'Guardar borrador', exact: true })).toBeFocused();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`borrador-${width}.png`) });
    const removed = await api(`/api/contratos/borradores/${saved.id}`, 'DELETE');
    expect(removed.status).toBe(204);
  });
}
